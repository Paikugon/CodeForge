
CREATE TABLE submissions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    problem_id BIGINT NOT NULL,
    language VARCHAR(30) NOT NULL,
    source_code TEXT NOT NULL,

    status VARCHAR(30) NOT NULL DEFAULT 'PENDING',
    verdict VARCHAR(30),

    execution_time_ms INTEGER,
    memory_used_kb INTEGER,

    passed_test_cases INTEGER NOT NULL DEFAULT 0,
    total_test_cases INTEGER NOT NULL DEFAULT 0,

    compile_output TEXT,
    error_message TEXT,

    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT fk_submissions_problem
        FOREIGN KEY (problem_id)
        REFERENCES problems(id),

    CONSTRAINT ck_submissions_status
        CHECK (status IN ('PENDING', 'JUDGING', 'COMPLETED', 'FAILED')),

    CONSTRAINT ck_submissions_verdict
        CHECK (
            verdict IS NULL OR verdict IN (
                'AC', 'WA', 'TLE', 'MLE',
                'RE', 'CE', 'SE'
            )
        )
);

CREATE INDEX idx_submissions_problem_id
    ON submissions(problem_id);

CREATE INDEX idx_submissions_created_at
    ON submissions(created_at DESC);
