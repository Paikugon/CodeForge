CREATE TABLE tags (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(50) NOT NULL,

    CONSTRAINT chk_tags_name_not_blank
        CHECK (name ~ '[^[:space:]]')
);

CREATE TABLE problem_tags (
    problem_id BIGINT NOT NULL,
    tag_id BIGINT NOT NULL,

    CONSTRAINT pk_problem_tags PRIMARY KEY (problem_id, tag_id),
    CONSTRAINT fk_problem_tags_problem
        FOREIGN KEY (problem_id)
        REFERENCES problems(id)
        ON DELETE CASCADE,
    CONSTRAINT fk_problem_tags_tag
        FOREIGN KEY (tag_id)
        REFERENCES tags(id)
        ON DELETE CASCADE
);

-- index to speed up queries filtering by problem_id
CREATE INDEX idx_problem_tags_tag_id ON problem_tags(tag_id);
